#include <vector>

struct SpectralSample {
    float wavelengthNm;
    float intensity;
};

struct Spectrum {
    std::vector<SpectralSample> samples;

    Spectrum() = default;

    explicit Spectrum(std::vector<SpectralSample> samples) : samples(std::move(samples)) {}

    Spectrum(const std::vector<float>& wavelengths, const std::vector<float>& intensities) {
        size_t count = std::min(wavelengths.size(), intensities.size());
        samples.reserve(count);
        for (size_t i = 0; i < count; i++) samples.push_back({wavelengths[i], intensities[i]});
    }
};

